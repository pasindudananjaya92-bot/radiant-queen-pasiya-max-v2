/**
 * /review — GitHub PR Auto-Reviewer (founder)
 * Fetches PR files + patch, AI review, optional comment post
 */
const GITHUB_TOKEN = () => process.env.GITHUB_TOKEN || '';
const GITHUB_REPO = () =>
  process.env.GITHUB_REPO || 'pasindudananjaya92-bot/radiant-queen-pasiya-max-v2';

function headers() {
  return {
    Authorization: `Bearer ${GITHUB_TOKEN()}`,
    Accept: 'application/vnd.github+json',
    'X-GitHub-Api-Version': '2022-11-28',
    'User-Agent': 'PasiyaOS-Review',
  };
}

async function gh(path) {
  const res = await fetch(`https://api.github.com/repos/${GITHUB_REPO()}${path}`, {
    headers: headers(),
  });
  const text = await res.text();
  let json = null;
  try {
    json = JSON.parse(text);
  } catch (_) {}
  if (!res.ok) {
    return { ok: false, error: `GitHub ${res.status}: ${text.slice(0, 180)}`, status: res.status };
  }
  return { ok: true, data: json };
}

async function aiReview(summary) {
  const groq = process.env.GROQ_API_KEY || '';
  const prompt =
    'You are a senior security + code reviewer. Review this PR diff summary.\n' +
    'Reply in under 1200 chars. Sections: 1) Risk (High/Med/Low) 2) Bugs 3) Security 4) Style 5) Verdict (approve/request changes).\n\n' +
    summary.slice(0, 14000);
  if (groq) {
    try {
      const res = await fetch('https://api.groq.com/openai/v1/chat/completions', {
        method: 'POST',
        headers: {
          Authorization: 'Bearer ' + groq,
          'Content-Type': 'application/json',
        },
        body: JSON.stringify({
          model: process.env.GROQ_MODEL || 'llama-3.3-70b-versatile',
          temperature: 0.2,
          max_tokens: 900,
          messages: [
            { role: 'system', content: 'Concise PR reviewer. No fluff.' },
            { role: 'user', content: prompt },
          ],
        }),
      });
      const j = await res.json();
      const t = j.choices?.[0]?.message?.content;
      if (t) return t.trim();
    } catch (_) {}
  }
  const gem = process.env.GEMINI_API_KEY || '';
  if (gem) {
    try {
      const url =
        'https://generativelanguage.googleapis.com/v1beta/models/gemini-2.0-flash:generateContent?key=' +
        encodeURIComponent(gem);
      const res = await fetch(url, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ contents: [{ parts: [{ text: prompt }] }] }),
      });
      const j = await res.json();
      const t = j.candidates?.[0]?.content?.parts?.[0]?.text;
      if (t) return t.trim();
    } catch (_) {}
  }
  return 'AI unavailable. Manual review required. Files listed above.';
}

export async function listOpenPrs(limit = 8) {
  if (!GITHUB_TOKEN()) return { ok: false, error: 'GITHUB_TOKEN missing' };
  const r = await gh('/pulls?state=open&per_page=' + Math.min(15, limit));
  if (!r.ok) return r;
  const rows = (r.data || []).map((p) => ({
    number: p.number,
    title: p.title,
    user: p.user?.login,
    updated: p.updated_at,
  }));
  return { ok: true, prs: rows };
}

export async function reviewPr(prNumber, { postComment = false } = {}) {
  if (!GITHUB_TOKEN()) return { ok: false, error: 'GITHUB_TOKEN missing' };
  const n = Number(prNumber);
  if (!n || n < 1) return { ok: false, error: 'Usage: /review <pr_number>  or /review list' };

  const meta = await gh('/pulls/' + n);
  if (!meta.ok) return meta;
  const files = await gh('/pulls/' + n + '/files?per_page=30');
  if (!files.ok) return files;

  const fileList = (files.data || [])
    .slice(0, 25)
    .map((f) => {
      const patch = String(f.patch || '').slice(0, 400);
      return `### ${f.filename} (+${f.additions}/-${f.deletions})\n${patch}`;
    })
    .join('\n\n');

  const header =
    `PR #${n}: ${meta.data.title}\n` +
    `by ${meta.data.user?.login} · ${meta.data.head?.ref} → ${meta.data.base?.ref}\n` +
    `files: ${(files.data || []).length}\n\n`;

  const review = await aiReview(header + fileList);
  let commented = false;
  if (postComment && review) {
    const body =
      '## PasiyaOS Auto-Review\n\n' + review + '\n\n_Generated by /review — founder bot_';
    const res = await fetch(
      `https://api.github.com/repos/${GITHUB_REPO()}/issues/${n}/comments`,
      {
        method: 'POST',
        headers: { ...headers(), 'Content-Type': 'application/json' },
        body: JSON.stringify({ body }),
      }
    );
    commented = res.ok;
  }

  return {
    ok: true,
    number: n,
    title: meta.data.title,
    review,
    commented,
    files: (files.data || []).length,
  };
}

export function formatReview(r) {
  if (!r.ok) return '❌ Review: ' + (r.error || 'fail');
  if (r.prs) {
    if (!r.prs.length) return '📋 No open PRs';
    return (
      '📋 OPEN PRs\n' +
      r.prs.map((p) => `#${p.number} ${p.title} (@${p.user})`).join('\n') +
      '\n\n/review <n> · /review <n> comment'
    );
  }
  return (
    `🔎 PR #${r.number} · ${r.title}\n` +
    `Files: ${r.files}` +
    (r.commented ? ' · 💬 commented' : '') +
    `\n\n${r.review}`
  ).slice(0, 3900);
}

export default { listOpenPrs, reviewPr, formatReview };
