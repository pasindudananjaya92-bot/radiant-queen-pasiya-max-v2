/**
 * lib/liveCanvas.js — /forgepage → public/canvas/<id>/index.html via GitHub API
 */
const GITHUB_TOKEN = process.env.GITHUB_TOKEN || '';
const GITHUB_REPO =
  process.env.GITHUB_REPO || 'pasindudananjaya92-bot/radiant-queen-pasiya-max-v2';
const SITE =
  process.env.MINIAPP_URL ||
  process.env.CHRONOS_HEALTH_URL ||
  'https://radiant-queen-pasiya-max-v2.vercel.app';

function ownerRepo() {
  const p = String(GITHUB_REPO).split('/');
  return { owner: p[0], repo: p[1] };
}

function ghHeaders() {
  return {
    Authorization: 'Bearer ' + GITHUB_TOKEN,
    Accept: 'application/vnd.github+json',
    'User-Agent': 'pasiya-live-canvas',
  };
}

export function makeCanvasId() {
  return (
    Date.now().toString(36) +
    Math.random().toString(36).slice(2, 8)
  );
}

export function buildHtml({ title, bodyHtml, prompt }) {
  const t = String(title || 'Pasiya Canvas').slice(0, 80);
  const body =
    bodyHtml ||
    `<main style="font-family:system-ui;padding:2rem;max-width:720px;margin:auto">
      <h1>${escape(t)}</h1>
      <p style="opacity:.75">Generated by PasiyaOS Live Canvas</p>
      <article style="line-height:1.6;white-space:pre-wrap">${escape(prompt || '')}</article>
    </main>`;
  return `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8"/>
<meta name="viewport" content="width=device-width,initial-scale=1"/>
<title>${escape(t)}</title>
<style>
  body{margin:0;background:#0b0b0f;color:#f5f5f7}
  a{color:#6cb6ff}
</style>
</head>
<body>
${body}
<footer style="text-align:center;opacity:.4;padding:2rem;font-size:12px">PasiyaOS · Live Canvas</footer>
</body>
</html>`;
}

function escape(s) {
  return String(s || '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

export async function githubPutFile(path, content, message) {
  const { owner, repo } = ownerRepo();
  if (!GITHUB_TOKEN) return { ok: false, error: 'GITHUB_TOKEN missing' };
  const url = `https://api.github.com/repos/${owner}/${repo}/contents/${path}`;
  // get existing sha if any
  let sha;
  try {
    const g = await fetch(url, { headers: ghHeaders() });
    if (g.ok) {
      const j = await g.json();
      sha = j.sha;
    }
  } catch (_) {}
  const body = {
    message: message || 'canvas: ' + path,
    content: Buffer.from(content, 'utf8').toString('base64'),
    branch: 'main',
  };
  if (sha) body.sha = sha;
  const res = await fetch(url, {
    method: 'PUT',
    headers: { ...ghHeaders(), 'Content-Type': 'application/json' },
    body: JSON.stringify(body),
  });
  const j = await res.json();
  if (!res.ok) return { ok: false, error: j.message || res.status };
  return { ok: true, url: j.content?.html_url, path };
}

/**
 * Optional AI HTML body — falls back to simple template
 */
export async function generatePageHtml(prompt) {
  const groq = process.env.GROQ_API_KEY || '';
  if (!groq) {
    return buildHtml({ title: 'Canvas', prompt });
  }
  try {
    const res = await fetch('https://api.groq.com/openai/v1/chat/completions', {
      method: 'POST',
      headers: {
        Authorization: 'Bearer ' + groq,
        'Content-Type': 'application/json',
      },
      body: JSON.stringify({
        model: process.env.GROQ_MODEL || 'llama-3.3-70b-versatile',
        messages: [
          {
            role: 'system',
            content:
              'Return ONLY a full HTML5 document (no markdown). Dark premium UI. Mobile friendly. No external scripts.',
          },
          { role: 'user', content: String(prompt).slice(0, 2000) },
        ],
        max_tokens: 2500,
        temperature: 0.5,
      }),
    });
    const j = await res.json();
    let html = j.choices?.[0]?.message?.content || '';
    html = html.replace(/^```html\s*/i, '').replace(/```\s*$/i, '').trim();
    if (html.includes('<html') || html.includes('<!DOCTYPE')) return html;
    return buildHtml({ title: 'Canvas', bodyHtml: html, prompt });
  } catch {
    return buildHtml({ title: 'Canvas', prompt });
  }
}

export async function forgePage(prompt) {
  const id = makeCanvasId();
  const html = await generatePageHtml(prompt);
  const path = `public/canvas/${id}/index.html`;
  const put = await githubPutFile(path, html, 'forgepage: ' + id);
  if (!put.ok) return put;
  const live = String(SITE).replace(/\/$/, '') + '/canvas/' + id + '/';
  return { ok: true, id, path, liveUrl: live, github: put.url };
}

export default { forgePage, buildHtml, generatePageHtml, makeCanvasId };
