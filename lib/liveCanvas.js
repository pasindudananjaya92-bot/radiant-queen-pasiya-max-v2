/**
 * lib/liveCanvas.js — /forgepage fix
 * 1) PUT public/canvas/<id>/index.html
 * 2) Verify via GET
 * 3) Trigger VERCEL_DEPLOY_HOOK so CDN picks it up
 * 4) Instant preview: raw.githubusercontent.com
 */
const GITHUB_TOKEN = process.env.GITHUB_TOKEN || '';
const GITHUB_REPO =
  process.env.GITHUB_REPO || 'pasindudananjaya92-bot/radiant-queen-pasiya-max-v2';
const GITHUB_BRANCH = process.env.GITHUB_BRANCH || 'main';
const SITE =
  process.env.MINIAPP_URL ||
  process.env.CHRONOS_HEALTH_URL ||
  'https://radiant-queen-pasiya-max-v2.vercel.app';
const VERCEL_DEPLOY_HOOK = process.env.VERCEL_DEPLOY_HOOK || '';

function ownerRepo() {
  const p = String(GITHUB_REPO).split('/');
  return { owner: p[0], repo: p[1] };
}

function ghHeaders() {
  return {
    Authorization: 'Bearer ' + GITHUB_TOKEN,
    Accept: 'application/vnd.github+json',
    'User-Agent': 'pasiya-live-canvas',
  };
}

export function makeCanvasId() {
  return Date.now().toString(36) + Math.random().toString(36).slice(2, 8);
}

function escape(s) {
  return String(s || '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

export function buildHtml({ title, bodyHtml, prompt }) {
  const t = String(title || 'Pasiya Canvas').slice(0, 80);
  const body =
    bodyHtml ||
    `<main style="font-family:system-ui;padding:2rem;max-width:720px;margin:auto">
      <h1>${escape(t)}</h1>
      <p style="opacity:.75">Generated by PasiyaOS Live Canvas</p>
      <article style="line-height:1.6;white-space:pre-wrap">${escape(prompt || '')}</article>
    </main>`;
  return `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8"/>
<meta name="viewport" content="width=device-width,initial-scale=1"/>
<title>${escape(t)}</title>
<style>
  body{margin:0;background:#0b0b0f;color:#f5f5f7}
  a{color:#6cb6ff}
</style>
</head>
<body>
${body}
<footer style="text-align:center;opacity:.4;padding:2rem;font-size:12px">PasiyaOS · Live Canvas</footer>
</body>
</html>`;
}

export async function githubPutFile(path, content, message) {
  const { owner, repo } = ownerRepo();
  if (!GITHUB_TOKEN) return { ok: false, error: 'GITHUB_TOKEN missing' };
  const url = `https://api.github.com/repos/${owner}/${repo}/contents/${path}`;
  let sha;
  try {
    const g = await fetch(url + '?ref=' + encodeURIComponent(GITHUB_BRANCH), {
      headers: ghHeaders(),
    });
    if (g.ok) {
      const j = await g.json();
      sha = j.sha;
    }
  } catch (_) {}
  const body = {
    message: message || 'canvas: ' + path,
    content: Buffer.from(content, 'utf8').toString('base64'),
    branch: GITHUB_BRANCH,
  };
  if (sha) body.sha = sha;
  const res = await fetch(url, {
    method: 'PUT',
    headers: { ...ghHeaders(), 'Content-Type': 'application/json' },
    body: JSON.stringify(body),
  });
  const j = await res.json();
  if (!res.ok) return { ok: false, error: j.message || res.status };
  return {
    ok: true,
    url: j.content?.html_url,
    path,
    sha: j.content?.sha,
    commit: j.commit?.sha,
  };
}

export async function githubGetFile(path) {
  const { owner, repo } = ownerRepo();
  const url =
    `https://api.github.com/repos/${owner}/${repo}/contents/${path}?ref=` +
    encodeURIComponent(GITHUB_BRANCH);
  const res = await fetch(url, { headers: ghHeaders() });
  if (!res.ok) return { ok: false, status: res.status };
  const j = await res.json();
  return { ok: true, sha: j.sha, size: j.size, html_url: j.html_url };
}

async function triggerDeployHook() {
  if (!VERCEL_DEPLOY_HOOK) return { ok: false, skipped: true };
  try {
    const res = await fetch(VERCEL_DEPLOY_HOOK, { method: 'POST' });
    return { ok: res.ok || res.status === 201, status: res.status };
  } catch (e) {
    return { ok: false, error: String(e.message || e) };
  }
}

export async function generatePageHtml(prompt) {
  const groq = process.env.GROQ_API_KEY || '';
  if (!groq) return buildHtml({ title: 'Canvas', prompt });
  try {
    const res = await fetch('https://api.groq.com/openai/v1/chat/completions', {
      method: 'POST',
      headers: {
        Authorization: 'Bearer ' + groq,
        'Content-Type': 'application/json',
      },
      body: JSON.stringify({
        model: process.env.GROQ_MODEL || 'llama-3.3-70b-versatile',
        messages: [
          {
            role: 'system',
            content:
              'Return ONLY a full HTML5 document (no markdown). Dark premium UI. Mobile friendly. No external scripts.',
          },
          { role: 'user', content: String(prompt).slice(0, 2000) },
        ],
        max_tokens: 2500,
        temperature: 0.5,
      }),
    });
    const j = await res.json();
    let html = j.choices?.[0]?.message?.content || '';
    html = html.replace(/^```html\s*/i, '').replace(/```\s*$/i, '').trim();
    if (html.includes('<html') || html.includes('<!DOCTYPE')) return html;
    return buildHtml({ title: 'Canvas', bodyHtml: html, prompt });
  } catch {
    return buildHtml({ title: 'Canvas', prompt });
  }
}

export async function forgePage(prompt) {
  const id = makeCanvasId();
  const html = await generatePageHtml(prompt);
  const path = `public/canvas/${id}/index.html`;
  const put = await githubPutFile(path, html, 'forgepage: ' + id);
  if (!put.ok) return put;

  // Verify on GitHub
  const verify = await githubGetFile(path);
  if (!verify.ok) {
    return {
      ok: false,
      error: 'GitHub PUT ok but verify GET failed (' + verify.status + '). Check branch=' + GITHUB_BRANCH,
    };
  }

  // Kick Vercel rebuild so /canvas/... is served
  const hook = await triggerDeployHook();

  const { owner, repo } = ownerRepo();
  const rawUrl =
    'https://raw.githubusercontent.com/' +
    owner +
    '/' +
    repo +
    '/' +
    GITHUB_BRANCH +
    '/' +
    path;
  const live = String(SITE).replace(/\/$/, '') + '/canvas/' + id + '/';
  const liveIndex = String(SITE).replace(/\/$/, '') + '/canvas/' + id + '/index.html';

  return {
    ok: true,
    id,
    path,
    liveUrl: live,
    liveIndexUrl: liveIndex,
    rawUrl,
    github: put.url || verify.html_url,
    deployHook: hook,
    tip: hook.ok
      ? 'Deploy hook fired — wait 30–90s then open live URL'
      : 'Set VERCEL_DEPLOY_HOOK for auto-redeploy; until then use rawUrl or /deploy now',
  };
}

export default { forgePage, buildHtml, generatePageHtml, makeCanvasId, githubPutFile };
