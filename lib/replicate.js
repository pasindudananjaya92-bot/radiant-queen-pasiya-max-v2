/**
 * /replicate — Self-replicating bot factory (blueprint mode, 100% free)
 * Does NOT burn Vercel function slots. Produces checklist + minimal stub files via forgeDrop.
 */
export function buildBlueprint(name = 'child-bot') {
  const n = String(name || 'child-bot')
    .toLowerCase()
    .replace(/[^a-z0-9-]/g, '-')
    .slice(0, 40);
  const env = [
    'BOT_TOKEN=',
    'ADMIN_ID=',
    'SUPABASE_URL=',
    'SUPABASE_SERVICE_ROLE_KEY=',
    'GITHUB_TOKEN=',
    'GITHUB_REPO=owner/' + n,
    'GROQ_API_KEY=',
    'GEMINI_API_KEY=',
    'CRON_SECRET=',
  ].join('\n');

  const minimalTg = `// Minimal child bot — api/telegram.js starter
import { Telegraf } from 'telegraf';
const bot = new Telegraf(process.env.BOT_TOKEN);
const ADMIN = String(process.env.ADMIN_ID || '');
bot.start((ctx) => ctx.reply('Child bot ${n} online'));
bot.command('ping', (ctx) => ctx.reply('pong · ${n}'));
bot.on('text', async (ctx) => {
  if (String(ctx.from?.id) !== ADMIN) return;
  await ctx.reply('Founder echo: ' + (ctx.message.text || '').slice(0, 200));
});
export default async (req, res) => {
  if (req.method === 'GET') return res.status(200).json({ ok: true, child: '${n}' });
  await bot.handleUpdate(req.body);
  res.status(200).json({ ok: true });
};
`;

  const readme = `# ${n} — PasiyaOS replicate blueprint

## Steps (phone-friendly)
1. BotFather → /newbot → copy token
2. GitHub → new repo \`${n}\`
3. Vercel → Import repo → set env (see env.example)
4. Supabase → new project OR reuse → run SQL from parent (SQL_GODMODE, REVENUE, CHAIN_AUDIT)
5. Set webhook: https://api.telegram.org/bot<token>/setWebhook?url=https://<vercel>.vercel.app/api/telegram
6. /ping on child bot

## Limits
- Vercel Hobby: max 12 serverless functions per project
- Keep api/ thin: telegram.js + health.js + cron.js only for child
- Parent bot stays founder-only; child gets its own ADMIN_ID

Generated by PasiyaOS /replicate
`;

  return {
    name: n,
    files: {
      'env.example': env,
      'api/telegram.js': minimalTg,
      'README_REPLICATE.md': readme,
    },
    checklist: [
      'BotFather /newbot',
      'GitHub empty repo: ' + n,
      'Vercel import + env',
      'Supabase SQL (godmode + chain)',
      'setWebhook → /api/telegram',
      'Test /ping',
    ],
  };
}

export async function replicateBlueprint(supabase, name) {
  const bp = buildBlueprint(name);
  // save checklist to pasiya_fs if available
  try {
    const fs = await import('../lib/pasiyaFs.js');
    const path = '/Documents/replicate/' + bp.name + '-checklist.txt';
    const body =
      'REPLICATE ' +
      bp.name +
      '\n\n' +
      bp.checklist.map((c, i) => i + 1 + '. ' + c).join('\n') +
      '\n\n' +
      bp.files['README_REPLICATE.md'];
    if (typeof fs.writeFile === 'function') {
      await fs.writeFile(supabase, path, body);
    } else if (typeof fs.fsWrite === 'function') {
      await fs.fsWrite(supabase, path, body);
    }
    bp.savedPath = path;
  } catch (_) {
    bp.savedPath = null;
  }
  return { ok: true, blueprint: bp };
}

export function formatBlueprint(r) {
  if (!r.ok) return '❌ ' + (r.error || 'fail');
  const bp = r.blueprint;
  const lines = [
    '🧬 REPLICATE BLUEPRINT',
    'name: ' + bp.name,
    '',
    'Checklist:',
    ...bp.checklist.map((c, i) => i + 1 + '. ' + c),
    '',
    bp.savedPath ? 'Saved: ' + bp.savedPath : 'Not saved to fs',
    '',
    'Child should use ≤3 api files (telegram, health, cron).',
    'Parent stays at 7/12 functions.',
    '',
    'Next: create BotFather token, then /forgedrop child telegram stub',
  ];
  return lines.join('\n').slice(0, 3500);
}

export default { buildBlueprint, replicateBlueprint, formatBlueprint };
